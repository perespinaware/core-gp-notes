"""Extract the 70 dermatology single-best-answer questions from the Core Dermatology PDF into akt/bank-derm.js.
Usage: python3 tools/make_derm_bank.py guides/Core_Dermatology_for_the_GP_AKT.pdf"""
import json,re,subprocess,sys
TOPICS=["Rosacea","Psoriasis","Lichen simplex, planus and sclerosus","Scabies","Acne vulgaris","Atopic eczema","Contact dermatitis"]
raw=subprocess.run(["pdftotext",sys.argv[1],"-"],capture_output=True,text=True).stdout
raw=re.sub(r"\n?Dermatology - AKT Revision Guide \|[^\n]*\n","\n",raw)
raw=re.sub(r"\n\s*Page \d+\s*\n","\n",raw).replace("\f","\n")
clean=lambda t:re.sub(r"\s+"," ",t).strip()
qblocks=re.split(r"5\. AKT QUESTIONS - 10 clinical scenarios",raw)[1:]
out=[]
for ti,blk in enumerate(qblocks):
    qpart,_,rest=blk.partition("5. ANSWER KEY AND EXPLANATIONS")
    qs=re.findall(r"Q(\d+)\.\s(.*?)\nA\.\s(.*?)\nB\.\s(.*?)\nC\.\s(.*?)\nD\.\s(.*?)\nE\.\s(.*?)(?=\nQ\d+\.|\Z)",qpart,re.S)
    keys=re.findall(r"\n(\d{1,2})\n\n([A-E])\n\n(.*?)(?=\n\d{1,2}\n\n[A-E]\n\n|\Z)",rest,re.S)[:10]
    assert len(qs)==10 and len(keys)==10,(TOPICS[ti],len(qs),len(keys))
    for (n,stem,*opts),(kn,let,why) in zip(qs,keys):
        assert n==kn,(TOPICS[ti],n,kn)
        if kn=="10": why=why.split("\n\n")[0]
        opts=[clean(o) for o in opts];e=clean(why)
        out.append({"id":f"derm-t{ti+1:02d}#{int(n)-1}","cat":"dermatology","topic":TOPICS[ti],"s":clean(stem),"o":opts,"a":"ABCDE".index(let),"e":e,"src":None})
open("akt/bank-derm.js","w").write("/* Core Dermatology for the GP AKT: 70 single-best-answer questions, generated by tools/make_derm_bank.py */\nconst DERM_BANK="+json.dumps(out,ensure_ascii=False).replace("<","\\u003c")+";\n")
print(len(out),"questions")
